function pythonExecutable (venv) {
  return process.platform === 'win32' ? join(venv, 'Scripts', 'python.exe') : join(venv, 'bin', 'python')
}

function createPythonRequirements (destination) {
  const venv = join(destination, '.portable-requirements-venv')
  command('python', ['-m', 'venv', venv], { cwd: destination })
  const python = pythonExecutable(venv)
  try {
    command(python, ['-m', 'pip', 'install', ...PYTHON_REQUIREMENTS], { cwd: destination })
    const requirements = command(python, ['-m', 'pip', 'freeze', '--all'], { cwd: destination, capture: true })
      .split(/\r?\n/)
      .map(line => line.trim())
      .filter(line => line && !line.startsWith('-e ') && !/^(pip|setuptools|wheel)==/i.test(line))
      .sort((a, b) => a.localeCompare(b))
    if (!requirements.length) throw new Error('Python dependency resolution returned no application packages')
    writeText(join(destination, 'requirements.txt'), `${requirements.join('\n')}\n`)
  } finally {
    rmSync(venv, { recursive: true, force: true })
  }
}

function installPortableRuntime (destination) {
  const scripts = join(destination, '.agent-standard', 'scripts')
  rmSync(scripts, { recursive: true, force: true })
  copyDirectory(runtimeRoot, scripts)
  rmSync(join(destination, '.agent-standard', 'copier-answers.yml'), { force: true })
  rmSync(join(destination, '.agent-standard', 'managed-skills.json'), { force: true })
  rmSync(join(destination, '.agent-standard', 'manifest.schema.json'), { force: true })
  rmSync(join(destination, '.ruler'), { recursive: true, force: true })
  rmSync(join(destination, 'openspec'), { recursive: true, force: true })
}

function createLockfilesAndSbom (destination, profile) {
  if (profile.python) createPythonRequirements(destination)
  else {
    rmSync(join(destination, 'package-lock.json'), { force: true })
    command(process.platform === 'win32' ? 'npm.cmd' : 'npm', ['install', '--package-lock-only', '--ignore-scripts'], { cwd: destination })
  }
  command(process.execPath, [join(destination, '.agent-standard', 'scripts', 'sbom.mjs'), '--write'], { cwd: destination })
}

function verifyBundle (destination, profile) {
  if (profile.python) {
    const venv = join(destination, '.portable-verify-venv')
    command('python', ['-m', 'venv', venv], { cwd: destination })
    const python = pythonExecutable(venv)
    try {
      command(python, ['-m', 'pip', 'install', '-r', 'requirements.txt'], { cwd: destination })
      const environment = { ...process.env, VIRTUAL_ENV: venv, PATH: `${dirname(python)}${delimiter}${process.env.PATH || ''}` }
      command(process.execPath, ['.agent-standard/scripts/verify.mjs'], { cwd: destination, env: environment })
    } finally {
      rmSync(venv, { recursive: true, force: true })
    }
  } else {
    const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm'
    command(npm, ['ci', '--ignore-scripts'], { cwd: destination })
    try { command(process.execPath, ['.agent-standard/scripts/verify.mjs'], { cwd: destination }) } finally {
      rmSync(join(destination, 'node_modules'), { recursive: true, force: true })
    }
  }
}

function removeVerificationArtifacts (destination) {
  for (const name of ['.next', 'dist', 'coverage', 'playwright-report', 'test-results', '.pytest_cache', '.mypy_cache', '.ruff_cache']) {
    rmSync(join(destination, name), { recursive: true, force: true })
  }
  for (const entry of readdirSync(destination, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue
    const path = join(destination, entry.name)
    if (entry.name === '__pycache__') rmSync(path, { recursive: true, force: true })
    else removeVerificationArtifacts(path)
  }
}

function assertPortable (destination) {
  const forbiddenPaths = [
    '.ruler', 'openspec', '.agent-standard/copier-answers.yml', '.agent-standard/managed-skills.json',
    '.agent-standard/manifest.schema.json', '.agent-standard/scripts/bootstrap.mjs',
    '.agent-standard/scripts/sync-skills.mjs', '.agent-standard/scripts/merge-config.mjs',
    '.agent-standard/scripts/doctor.mjs', 'uv.lock'
  ]
  for (const path of forbiddenPaths) if (existsSync(join(destination, path))) throw new Error(`${relative(destination, join(destination, path))} is not portable`)
  if (existsSync(join(destination, 'package.json'))) {
    const pkg = readJson(join(destination, 'package.json'))
    if (pkg.devDependencies?.['@playwright/test'] || Object.values(pkg.scripts || {}).some(command => /playwright|test:e2e/i.test(command))) {
      throw new Error('portable bundles must not require a browser test runtime')
    }
  }
  for (const path of ['e2e', 'playwright.config.ts']) {
    if (existsSync(join(destination, path))) throw new Error(`${path} requires a browser test runtime`)
  }

  for (const path of filesBelow(destination)) {
    if (/node_modules\//.test(path) || /\.portable-/.test(path)) throw new Error(`${path} must not be shipped`)
    const content = readFileSync(join(destination, path), 'utf8')
    for (const name of PROHIBITED) {
      if (new RegExp(`\\b${name}\\b`, 'i').test(content)) throw new Error(`${path} references a prohibited package: ${name}`)
    }
  }
}

function tarNumber (value, length) {
  return `${value.toString(8).padStart(length - 1, '0')}\0`
}

function tarString (header, offset, length, value) {
  Buffer.from(value).copy(header, offset, 0, Math.min(Buffer.byteLength(value), length))
}

function tarEntry (name, body) {
  const header = Buffer.alloc(512)
  tarString(header, 0, 100, name)
  tarString(header, 100, 8, tarNumber(0o644, 8))
  tarString(header, 108, 8, tarNumber(0, 8))
  tarString(header, 116, 8, tarNumber(0, 8))
  tarString(header, 124, 12, tarNumber(body.length, 12))
  tarString(header, 136, 12, tarNumber(0, 12))
  header.fill(0x20, 148, 156)
  header[156] = '0'.charCodeAt(0)
  tarString(header, 257, 6, 'ustar')
  tarString(header, 263, 2, '00')
  const checksum = [...header].reduce((total, value) => total + value, 0)
  tarString(header, 148, 8, tarNumber(checksum, 8))
  const padding = Buffer.alloc((512 - (body.length % 512)) % 512)
  return Buffer.concat([header, body, padding])
}

function createArchive (releaseRoot, target) {
  const top = `agent-standard-portable-${version}`
  const entries = filesBelow(releaseRoot).sort().map(path => tarEntry(`${top}/${path}`, readFileSync(join(releaseRoot, path))))
  const archive = gzipSync(Buffer.concat([...entries, Buffer.alloc(1024)]), { mtime: 0 })
  mkdirSync(dirname(target), { recursive: true })
  writeFileSync(target, archive)
}

function archiveNames (path) {
  const tar = gunzipSync(readFileSync(path))
  const names = []
  for (let offset = 0; offset + 512 <= tar.length;) {
    const name = tar.subarray(offset, offset + 100).toString('utf8').replace(/\0.*$/, '')
    if (!name) break
    const size = Number.parseInt(tar.subarray(offset + 124, offset + 136).toString('utf8').replace(/\0.*$/, '').trim(), 8)
    names.push(name)
    offset += 512 + Math.ceil(size / 512) * 512
  }
  return names
}

export function buildPortableRelease (target = output) {
  const revision = git(['rev-parse', 'HEAD'])
  validateReleaseSource(revision, git(['status', '--porcelain', '--untracked-files=all']))
  const staging = mkdtempSync(join(tmpdir(), 'agent-standard-portable-'))
  const releaseRoot = join(staging, `agent-standard-portable-${version}`)
  mkdirSync(releaseRoot, { recursive: true })
  try {
    copyFileSync(join(portableRoot, 'README.md'), join(releaseRoot, 'README.md'))
    const bundlesRoot = join(releaseRoot, 'bundles')
    mkdirSync(bundlesRoot, { recursive: true })
    const profiles = readdirSync(profilesRoot).filter(name => name.endsWith('.yml')).sort().map(name => profileDetails(join(profilesRoot, name)))
    for (const profile of profiles) {
      const destination = join(bundlesRoot, profile.id)
      command('uvx', [
        '--from', 'copier==9.17.2', 'copier', 'copy', '--trust', '--defaults',
        '--answers-file', '.agent-standard/copier-answers.yml', '--vcs-ref', revision,
        '--data', `standard_revision=${revision}`, '--data-file', profile.path, root, destination
      ])
      installPortableRuntime(destination)
      rewriteManifestAndGate(destination, profile)
      replacePortableGuidance(destination, profile)
      removeBrowserRuntime(destination, profile)
      if (profile.platform === 'github') writeGitHubWorkflow(destination, profile)
      else writeAzurePipeline(destination, profile)
      createLockfilesAndSbom(destination, profile)
      assertPortable(destination)
      verifyBundle(destination, profile)
      removeVerificationArtifacts(destination)
      assertPortable(destination)
    }
    const manifest = {
      format: 'agent-standard-portable',
      version,
      sourceRevision: revision,
      digestFormat: 'sha256-file-inventory-v1',
      hostPrerequisites: { git: '>=2.27', node: '>=22.13', python: '>=3.11 (Python bundles only)' },
      bundles: profiles.map(profile => ({
        id: profile.id,
        stack: profile.stack,
        platform: profile.platform,
        ...fingerprintBundle(join(bundlesRoot, profile.id))
      }))
    }
    writeJson(join(releaseRoot, 'RELEASE-MANIFEST.json'), manifest)
    assertPortable(releaseRoot)
    createArchive(releaseRoot, target)
    const names = archiveNames(target)
    if (names.some(name => /(^|\/)(?:\.ruler|openspec|node_modules)(?:\/|$)/.test(name))) throw new Error('archive contains a prohibited directory')
    return { target, manifest, names }
  } finally {
    rmSync(staging, { recursive: true, force: true })
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const result = buildPortableRelease()
    console.log(`portable release built: ${result.target}`)
    console.log(`profiles: ${result.manifest.bundles.map(bundle => bundle.id).join(', ')}`)
  } catch (error) {
    console.error(`portable release build failed: ${error.message}`)
    process.exitCode = 1
  }
}
