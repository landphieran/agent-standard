function command (program, commandArgs, options = {}) {
  const result = spawnSync(program, commandArgs, {
    cwd: options.cwd || root,
    encoding: 'utf8',
    stdio: options.capture ? 'pipe' : 'inherit',
    env: options.env || process.env,
    shell: options.shell ?? (process.platform === 'win32' && /\.cmd$/i.test(program))
  })
  if (result.status !== 0) {
    const detail = options.capture ? (result.stderr || result.stdout || result.error?.message || '').trim() : result.error?.message || ''
    throw new Error(`${program} ${commandArgs.join(' ')} failed${detail ? `: ${detail}` : ''}`)
  }
  return options.capture ? result.stdout : ''
}

function git (gitArgs) {
  return command('git', gitArgs, { capture: true }).trim()
}

export function validateReleaseSource (revision, status) {
  if (!/^[0-9a-f]{40}$/i.test(revision)) throw new Error('portable release requires a full source revision')
  if (status.trim()) throw new Error('portable release requires a clean source checkout')
}

function copyDirectory (source, destination) {
  mkdirSync(destination, { recursive: true })
  for (const entry of readdirSync(source, { withFileTypes: true })) {
    const from = join(source, entry.name)
    const to = join(destination, entry.name)
    if (entry.isDirectory()) copyDirectory(from, to)
    else if (entry.isFile()) copyFileSync(from, to)
  }
}

function filesBelow (directory, prefix = '') {
  return readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const child = prefix ? `${prefix}/${entry.name}` : entry.name
    const path = join(directory, entry.name)
    return entry.isDirectory() ? filesBelow(path, child) : [child]
  })
}

export function fingerprintBundle (directory) {
  const files = filesBelow(directory).sort().map(path => ({
    path,
    sha256: createHash('sha256').update(readFileSync(join(directory, path))).digest('hex')
  }))
  return {
    sha256: createHash('sha256').update(JSON.stringify(files)).digest('hex'),
    files
  }
}

function readJson (path) {
  return JSON.parse(readFileSync(path, 'utf8').replace(/^\uFEFF/, ''))
}

function writeJson (path, value) {
  writeFileSync(path, JSON.stringify(value, null, 2) + '\n')
}

function writeText (path, value) {
  writeFileSync(path, value.replace(/\r?\n/g, '\n').replace(/\n?$/, '\n'))
}

function profileDetails (path) {
  const text = readFileSync(path, 'utf8')
  const answer = key => text.match(new RegExp(`^${key}:\\s*([^\\r\\n]+)$`, 'm'))?.[1]?.trim().replace(/^['"]|['"]$/g, '')
  const stack = answer('language_stack')
  const platform = answer('repository_platform')
  if (!['ts-node', 'ts-next', 'py-fastapi'].includes(stack) || !['github', 'azure-devops'].includes(platform)) {
    throw new Error(`${basename(path)} has an unsupported portable profile`)
  }
  return { id: basename(path, '.yml'), path, stack, platform, python: stack === 'py-fastapi' }
}

function staticInstructions (path) {
  if (!existsSync(path)) return
  let text = readFileSync(path, 'utf8')
  text = text
    .replace(/<!-- Generated by Ruler -->\s*/gi, '')
    .replace(/<!-- Source: \.ruler\/[^>]+ -->\s*/gi, '')
    .replace(/Shared operating manual for every AI agent in this repo\. Generated by agent-standard;\s*ruler fans it to each tool\. Edit `\.ruler\/`, then run `ruler apply`[^\n]*\s*`CLAUDE\.md` \/ `AGENTS\.md`\./i,
      'Shared operating manual for every AI agent in this repository. The portable bundle contains committed instruction files for each selected client; maintain matching instructions together.')
    .replace(/Below this file, ruler appends the \*\*language standards\*\* and the \*\*architecture\s*standards\*\* for this project\. Follow all three\./i,
      'The language and architecture standards below are part of this portable bundle. Follow all of them.')
    .replace(/- Agent rulebook source[^\n]*\n/gi,
      '- Agent instructions → `AGENTS.md`, `CLAUDE.md`, and the tracked client skill directories\n')
    .replace('Python 3.11+, FastAPI, Pydantic v2, `uv`, Ruff', 'Python 3.11+, FastAPI, Pydantic v2, pip, Ruff')
    .replace(/- `uv` for env \+ deps \(`uv add`, `uv run`, commit `uv\.lock`\)\. \*\*Ruff\*\* as the single lint\+format tool \(replaces Black\/isort\/flake8\)\. Type-check with `uv run python -m mypy` \(or strict `pyright`\) in CI\. All tool config in `pyproject\.toml`\./,
      '- Use `python -m venv` and `python -m pip` for the environment and committed requirements. **Ruff** is the single lint-and-format tool; run type checks with `python -m mypy` in CI. Keep tool configuration in `pyproject.toml`.')
    .replace('Vitest + Playwright,', 'Vitest,')
    .replace(/- \*\*Do not unit-test async Server Components with Vitest\*\* \(unsupported\) — cover those with \*\*Playwright\*\* e2e, along with data-fetch flows and Server Action mutations\./,
      '- Do not unit-test async Server Components with Vitest; exercise them through focused integration coverage.')
  writeText(path, text)
}

function staticSkills (destination) {
  for (const clientRoot of ['.agents/skills', '.claude/skills', '.github/skills']) {
    const source = join(destination, clientRoot)
    if (!existsSync(source)) continue
    for (const path of filesBelow(source)) {
      if (!path.endsWith('/SKILL.md') && path !== 'SKILL.md') continue
      const absolute = join(source, path)
      const text = readFileSync(absolute, 'utf8')
        .split(/\r?\n/)
        .filter(line => !/\bspec-driven\b|\bopenspec\b/i.test(line))
        .join('\n')
        .replace('Follow `manifest.workflow.profile`:', 'Use the lightweight planning workflow:')
      writeText(absolute, text)
    }
  }
}

function replacePortableGuidance (destination, profile) {
  const readmePath = join(destination, 'README.md')
  let readme = readFileSync(readmePath, 'utf8')
  readme = readme
    .replace(/- \*\*Agent rulebook\*\*[^\n]*\n/,
      '- **Agent instructions** — tracked instruction files and client skill directories are included in this starter repository.\n')
    .replace(/## Updating the standard[\s\S]*$/,
      `## Refreshing this starter repository\n\nThis is the static \`${profile.id}\` portable starter repository. To adopt a newer baseline, compare this repository with the same bundle from a reviewed newer portable release, apply the selected changes, refresh the SBOM, run verification, and commit the result together.\n`)
  if (profile.python) {
    readme = readme
      .replace('| Package manager | `uv` |', '| Package manager | `pip` |')
      .replace(/uv sync/g, 'python -m pip install -r requirements.txt')
  }
  writeText(readmePath, readme)

  const contributingPath = join(destination, 'CONTRIBUTING.md')
  let contributing = readFileSync(contributingPath, 'utf8')
  contributing = contributing.replace(/Generated agent files are committed\.[\s\S]*$/,
    'Agent instructions and client skills are committed static files in this portable starter repository. Keep matching client instructions aligned when making a policy change.\n')
  writeText(contributingPath, contributing)

  staticInstructions(join(destination, 'AGENTS.md'))
  staticInstructions(join(destination, 'CLAUDE.md'))
  staticSkills(destination)
}

function rewriteManifestAndGate (destination, profile) {
  const manifestPath = join(destination, '.agent-standard', 'manifest.json')
  const manifest = readJson(manifestPath)
  delete manifest.$schema
  manifest.workflow = { profile: 'lightweight', engine: 'native' }
  if (profile.python) {
    manifest.project.packageManager = 'pip'
    manifest.commands.install = 'python -m pip install -r requirements.txt'
    manifest.commands.updateBom = 'node .agent-standard/scripts/sbom.mjs --write'
  }
  writeJson(manifestPath, manifest)

  const gatePath = join(destination, '.agent-standard', 'gate.json')
  const gate = readJson(gatePath)
  delete gate.doctorCommand
  delete gate.openspec
  delete gate.openspecValidateCommand
  if (profile.python) {
    gate.unitCommand = 'python -m pytest tests/unit -q'
    gate.fullCommand = 'python -m ruff format --check . && python -m ruff check . && python -m mypy src && python -m pytest -q'
  }
  if (profile.stack === 'ts-next') {
    gate.integrationTestGlobs = (gate.integrationTestGlobs || []).filter(glob => !glob.startsWith('e2e/'))
  }
  writeJson(gatePath, gate)
}

function removeBrowserRuntime (destination, profile) {
  const gitignorePath = join(destination, '.gitignore')
  if (existsSync(gitignorePath)) {
    writeText(gitignorePath, readFileSync(gitignorePath, 'utf8')
      .split(/\r?\n/)
      .filter(line => !/playwright|test-results/i.test(line))
      .join('\n'))
  }
  for (const path of [join(destination, 'ARCHITECTURE.md'), join(destination, 'docs', 'testing.md')]) {
    if (!existsSync(path)) continue
    writeText(path, readFileSync(path, 'utf8')
      .replace(/^.*e2e\/.*(?:\r?\n|$)/gmi, '')
      .replace(/^.*playwright.*(?:\r?\n|$)/gmi, '')
      .replace(/^\| End-to-end \|.*(?:\r?\n|$)/gmi, ''))
  }
  if (profile.stack !== 'ts-next') return
  const packagePath = join(destination, 'package.json')
  const pkg = readJson(packagePath)
  pkg.scripts.lint = 'eslint app src __tests__ vitest.config.ts'
  pkg.scripts.test = 'npm run test:unit'
  delete pkg.scripts['test:e2e']
  delete pkg.devDependencies['@playwright/test']
  writeJson(packagePath, pkg)
  rmSync(join(destination, 'e2e'), { recursive: true, force: true })
  rmSync(join(destination, 'playwright.config.ts'), { force: true })
}

